package community

import (
	"github.com/gin-gonic/gin"
	"github.com/kasuganosora/community/controllers/api/admin"
	"github.com/kasuganosora/community/middleware"
	"github.com/kasuganosora/community/models"
)

func registerAdminManagementRoutes(public, auth *gin.RouterGroup) {
	read := auth.Group("/admin", middleware.CheckScopeMiddleware(middleware.Scope{Type: models.AppScopeTypeAdmin, Value: models.AppScopeAdminRead}))
	write := auth.Group("/admin", middleware.CheckScopeMiddleware(middleware.Scope{Type: models.AppScopeTypeAdmin, Value: models.AppScopeAdminWrite}))
	read.GET("/discovery/status", admin.DiscoveryStatus)
	read.GET("/discovery/feedback", admin.ListDiscoveryFeedback)
	write.POST("/discovery/feedback", admin.CreateDiscoveryFeedback)
	write.POST("/discovery/approve", admin.ApproveDiscoveryIndex)
	write.DELETE("/discovery/feedback/:id", admin.DeleteDiscoveryFeedback)
	read.GET("/analytics", admin.GetAnalytics)
	read.GET("/email_domain_blocks", admin.ListEmailDomainBlocks)
	read.GET("/email_domain_blocks/:id", admin.GetEmailDomainBlock)
	write.POST("/email_domain_blocks", admin.CreateEmailDomainBlock)
	write.DELETE("/email_domain_blocks/:id", admin.DeleteEmailDomainBlock)
	read.GET("/roles", admin.ListRoles)
	read.GET("/roles/:id/users", admin.ListRoleMembers)
	write.POST("/roles", admin.CreateRole)
	write.PUT("/roles/:id", admin.UpdateRole)
	write.DELETE("/roles/:id", admin.DeleteRole)
	write.POST("/roles/:id/users/:account_id", admin.AssignAdminRole)
	write.DELETE("/roles/:id/users/:account_id", admin.UnassignAdminRole)
	read.GET("/invites", admin.ListAdminInvites)
	write.POST("/invites", admin.CreateAdminInvites)
	write.PUT("/invites/:id", admin.UpdateAdminInvite)
	read.GET("/audit-logs", admin.ListAuditLogs)
	read.GET("/announcements", admin.ListAdminAnnouncements)
	read.GET("/announcements/:id", admin.GetAdminAnnouncement)
	write.POST("/announcements", admin.SaveAdminAnnouncement)
	write.PUT("/announcements/:id", admin.SaveAdminAnnouncement)
	write.DELETE("/announcements/:id", admin.DeleteAdminAnnouncement)
	write.POST("/announcements/:id/publish", admin.PublishAdminAnnouncement)
	write.POST("/announcements/:id/unpublish", admin.UnpublishAdminAnnouncement)
	read.GET("/settings/:section", admin.GetSettings)
	write.PUT("/settings/:section", admin.UpdateSettings)
	write.POST("/settings/email/test", admin.TestEmailSettings)
	write.POST("/settings/storage/test", admin.TestStorageSettings)
	read.GET("/federation/instances", admin.FederationInstances)
	read.GET("/federation/jobs", admin.FederationJobs)
	write.POST("/federation/jobs/:kind/:id/action", admin.FederationJobAction)
	read.GET("/federation/queue-stats", admin.FederationQueueStats)
	read.GET("/federation/queue-hosts", admin.FederationQueueHosts)
	write.POST("/federation/queue-bulk/:kind", admin.FederationQueueBulk)
	read.GET("/oauth_applications", admin.ListOAuthApplications)
	write.DELETE("/oauth_applications/:id", admin.DeleteOAuthApplication)
	read.GET("/webhooks", admin.Webhooks)
	write.POST("/webhooks", admin.CreateWebhook)
	write.PUT("/webhooks/:id", admin.UpdateWebhook)
	write.POST("/webhooks/:id/:action", admin.WebhookAction)
	read.GET("/webhook-deliveries", admin.WebhookDeliveries)
	write.POST("/webhook-deliveries/:id/action", admin.WebhookDeliveryAction)
	read.GET("/files", admin.ListManagedFiles)
	write.DELETE("/files/:id", admin.DeleteManagedFile)
	read.GET("/avatar_decorations", admin.ListAvatarDecorations)
	write.POST("/avatar_decorations", admin.CreateAvatarDecoration)
	write.PATCH("/avatar_decorations/:id", admin.UpdateAvatarDecoration)
	write.DELETE("/avatar_decorations/:id", admin.DeleteAvatarDecoration)
	read.GET("/advertisements", admin.ListAdvertisements)
	write.POST("/advertisements", admin.CreateAdvertisement)
	write.PATCH("/advertisements/:id", admin.UpdateAdvertisement)
	write.DELETE("/advertisements/:id", admin.DeleteAdvertisement)
	public.GET("/avatar_decorations", admin.PublicAvatarDecorations)
	public.GET("/avatar_decorations/:id/image", admin.AvatarDecorationImage)
	public.GET("/advertisements", admin.PublicAdvertisements)
	auth.PUT("/accounts/avatar_decoration", middleware.CheckScopeMiddleware(middleware.Scope{Type: models.AppScopeTypeWrite, Value: models.AppScopeWriteAccounts}), admin.SelectAvatarDecoration)
}
