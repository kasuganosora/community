/** Messages with a variable part; capture groups become {0}, {1}… */
const API_ERROR_PATTERNS: ReadonlyArray<readonly [RegExp, string]> = [
  [/^invalid request: .+$/i, 'invalidRequest'],
  [/^Invalid query parameters: .+$/i, 'invalidRequest'],
  [/^Validation failed: (.+)$/i, 'validationFailed'],
  [/^limit must be between 1 and (\d+)$/i, 'listLimitRange'],
  [/^limit must be 1–(\d+)$/i, 'limitRange'],
  [/^Invalid ([a-z_]+)$/i, 'invalidField'],
  [/^at most (\d+) decorations may be selected$/i, 'decorationLimit'],
  [/^API rate limit exceeded for .*$/i, 'rateLimited'],
  [/^invalid value for ([\w.:-]+)$/i, 'settingValueInvalid'],
]

/** Localized text for a backend error message, or null when unmapped. */
export function translateApiError(message: string | null | undefined): string | null {
  if (!message) return null
  const trimmed = message.trim()
  const key = API_ERRORS[trimmed.toLowerCase()]
  if (key) return t(`apiError.${key}`)
  for (const [pattern, patternKey] of API_ERROR_PATTERNS) {
    const match = pattern.exec(trimmed)
    if (!match) continue
    // A wrapped detail ("Validation failed: <detail>") reads best when the
    // detail itself is translated; the wrapper then adds nothing.
    if (patternKey === 'validationFailed') {
      const inner = translateApiError(match[1])
      if (inner) return inner
    }
    return t(`apiError.${patternKey}`, match.slice(1))
  }
  return null
}

