const matrixMediaLimit int64 = 50 << 20

type federationMedia struct {
	Data                  []byte
	ContentType, Filename string
}

// Authenticated media federation (Matrix 1.11). The first part is metadata;
// the second contains the original bytes, including encrypted attachment bytes.
func handleFederationMediaDownload(c *gin.Context) {
	hs := GetHomeServer()
	m, r, err := NewMediaService(hs).GetMedia(hs.Config.ServerName, c.Param("mediaId"))
	if err != nil {
		c.JSON(404, gin.H{"errcode": "M_NOT_FOUND", "error": "Media not found"})
		return
	}
	defer r.Close()
	writeFederationMedia(c, r, m.ContentType, m.FileName)
}
func handleFederationMediaThumbnail(c *gin.Context) {
	hs := GetHomeServer()
	w, _ := strconv.Atoi(c.DefaultQuery("width", "320"))
	h, _ := strconv.Atoi(c.DefaultQuery("height", "240"))
	if w < 1 || h < 1 || w > 4096 || h > 4096 {
		c.JSON(400, gin.H{"errcode": "M_INVALID_PARAM", "error": "Invalid thumbnail dimensions"})
		return
	}
	_, r, err := NewMediaService(hs).GetThumbnail(hs.Config.ServerName, c.Param("mediaId"), w, h, c.DefaultQuery("method", "scale"))
	if err != nil {
		c.JSON(404, gin.H{"errcode": "M_NOT_FOUND", "error": "Thumbnail not found"})
		return
	}
	defer r.Close()
	// Detect actual bytes: the thumbnail service may return the original PNG.
	prefix := make([]byte, 512)
	n, _ := io.ReadFull(r, prefix)
	prefix = prefix[:n]
	writeFederationMedia(c, io.MultiReader(bytes.NewReader(prefix), r), http.DetectContentType(prefix), "thumbnail")
}
func writeFederationMedia(c *gin.Context, r io.Reader, contentType, filename string) {
	boundary := multipart.NewWriter(io.Discard).Boundary()
	c.Header("Content-Type", "multipart/mixed; boundary="+boundary)
	c.Header("X-Content-Type-Options", "nosniff")
	// Synapse's streaming multipart parser expects Content-Type before other
	// headers in the file part. Go's CreatePart sorts Content-Disposition first.
	// Values are generated by MIME formatters, never raw untrusted header text.
	parsedType, params, err := mime.ParseMediaType(contentType)
	if err != nil {
		parsedType = "application/octet-stream"
		params = nil
	}
	contentType = mime.FormatMediaType(parsedType, params)
	disposition := mime.FormatMediaType("inline", map[string]string{"filename": filename})
	if _, err = fmt.Fprintf(c.Writer, "--%s\r\nContent-Type: application/json\r\n\r\n{}\r\n--%s\r\nContent-Type: %s\r\nContent-Disposition: %s\r\n\r\n", boundary, boundary, contentType, disposition); err != nil {
		return
	}
	if _, err = io.Copy(c.Writer, r); err != nil {
		return
	}
	_, _ = fmt.Fprintf(c.Writer, "\r\n--%s--\r\n", boundary)
}
func (c *FederationClient) fetchAuthenticatedMedia(serverName, mediaID, kind, query string) (*federationMedia, error) {
	return c.fetchAuthenticatedMediaContext(context.Background(), serverName, mediaID, kind, query)
}
func (c *FederationClient) fetchAuthenticatedMediaContext(ctx context.Context, serverName, mediaID, kind, query string) (*federationMedia, error) {
	base := c.federationBaseURL(serverName)
	parsed, parseErr := url.Parse(base)
	// MXC server names are authorities, never URLs. Reject URL components so
	// encoded #/?/@ cannot move the media route into a fragment/query or alter
	// the host and bypass selection of its SSRF-protected transport.
	if parseErr != nil || parsed.Hostname() == "" || parsed.User != nil || parsed.Path != "" || parsed.RawQuery != "" || parsed.Fragment != "" {
		return nil, fmt.Errorf("invalid media server name")
	}
	target := base + "/_matrix/federation/v1/media/" + kind + "/" + url.PathEscape(mediaID) + query
	req, err := c.prepareSignedFederationRequest(ctx, "GET", target, serverName, nil)
	if err != nil {
		return nil, err
	}
	resp, err := c.federationMediaHTTPClient().Do(req)
	if err != nil {
		return nil, fmt.Errorf("failed to fetch media: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("remote media HTTP %d", resp.StatusCode)
	}
	return parseFederationMediaReader(resp.Header.Get("Content-Type"), io.LimitReader(resp.Body, matrixMediaLimit+(1<<20)))
}
func parseFederationMedia(contentType string, raw []byte) (*federationMedia, error) {
	return parseFederationMediaReader(contentType, bytes.NewReader(raw))
}
func parseFederationMediaReader(contentType string, raw io.Reader) (*federationMedia, error) {
	return parseFederationMediaBounded(contentType, raw, matrixMediaLimit)
}
func parseFederationMediaBounded(contentType string, raw io.Reader, limit int64) (*federationMedia, error) {
	typ, params, err := mime.ParseMediaType(contentType)
	if err != nil || typ != "multipart/mixed" || params["boundary"] == "" {
		return nil, fmt.Errorf("invalid federation media multipart response")
	}
	reader := multipart.NewReader(raw, params["boundary"])
	metadata, err := reader.NextPart()
	if err != nil {
		return nil, err
	}
	meta, err := io.ReadAll(io.LimitReader(metadata, 65537))
	if err != nil || len(meta) > 65536 || !json.Valid(meta) {
		return nil, fmt.Errorf("invalid media metadata")
	}
	body, err := reader.NextPart()
	if err != nil {
		return nil, err
	}
	// Remote redirects are intentionally not followed: fetching an arbitrary
	// Location from a multipart body would evade the federation SSRF policy.
	if body.Header.Get("Location") != "" {
		return nil, fmt.Errorf("remote media redirect not supported")
	}
	data, err := io.ReadAll(io.LimitReader(body, limit+1))
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > limit {
		return nil, fmt.Errorf("remote media too large")
	}
	if _, err := reader.NextPart(); err != io.EOF {
		return nil, fmt.Errorf("invalid trailing media multipart part")
	}
	mediaType := body.Header.Get("Content-Type")
	if mediaType == "" {
		mediaType = "application/octet-stream"
	}
	_, disposition, _ := mime.ParseMediaType(body.Header.Get("Content-Disposition"))
	return &federationMedia{Data: data, ContentType: mediaType, Filename: filepath.Base(strings.ReplaceAll(disposition["filename"], "\\", "/"))}, nil
}

